/**
 * Biz Care + Biz Collection `*sum*.csv` under `data/supplier/fashion-biz/csv/`:
 *   - style → short_description → `lib/biz-care-collection-style-titles.generated.ts`
 *   - style → stringified_description → `lib/biz-care-collection-style-details.generated.ts`
 *
 * Uses the CSV header row (same idea as `scripts/lib/fashion-biz-sum-csv-maps.mjs`).
 *
 * Run: node scripts/generate-biz-care-collection-style-titles.mjs
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { getBossWebRoot } from "./lib/load-env.mjs";

function splitCsvFields(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i += 1) {
    const c = line[i];
    if (c === '"') {
      q = !q;
      continue;
    }
    if (c === "," && !q) {
      out.push(cur);
      cur = "";
      continue;
    }
    cur += c;
  }
  out.push(cur);
  return out;
}

function main() {
  const root = getBossWebRoot();
  const csvDir = join(root, "data", "supplier", "fashion-biz", "csv");
  const shortMap = new Map();
  const detailMap = new Map();

  if (!existsSync(csvDir)) {
    console.warn("Missing CSV dir:", csvDir);
  } else {
    let files;
    try {
      files = readdirSync(csvDir).filter((f) => {
        const l = f.toLowerCase();
        return (
          l.endsWith(".csv") &&
          l.includes("sum") &&
          (l.includes("biz-care") || l.includes("biz-collection"))
        );
      });
    } catch {
      files = [];
    }
    files.sort();
    for (const file of files) {
      let text;
      try {
        text = readFileSync(join(csvDir, file), "utf8");
      } catch {
        continue;
      }
      const lines = text.split(/\r?\n/);
      if (!lines.length) {
        continue;
      }
      const headerCols = splitCsvFields(lines[0]).map((h) => String(h).trim());
      const idxStyle = headerCols.findIndex((h) => h.toLowerCase() === "style");
      const idxShort = headerCols.findIndex((h) => h.toLowerCase() === "short_description");
      const idxDetail = headerCols.findIndex((h) => h.toLowerCase() === "stringified_description");
      if (idxStyle < 0) {
        continue;
      }
      if (idxShort < 0 && idxDetail < 0) {
        continue;
      }
      for (let li = 1; li < lines.length; li += 1) {
        const line = lines[li];
        if (!line.trim()) {
          continue;
        }
        const cols = splitCsvFields(line);
        const maxIdx = Math.max(idxStyle, idxShort, idxDetail);
        if (cols.length <= maxIdx) {
          continue;
        }
        const style = String(cols[idxStyle] ?? "")
          .trim()
          .toUpperCase()
          .replace(/-CLEARANCE$/i, "");
        if (!style) {
          continue;
        }
        if (idxShort >= 0) {
          const shortDesc = String(cols[idxShort] ?? "").trim();
          if (shortDesc) {
            shortMap.set(style, shortDesc);
          }
        }
        if (idxDetail >= 0) {
          const detail = String(cols[idxDetail] ?? "")
            .trim()
            .replace(/\r\n/g, "\n");
          if (detail) {
            const prev = detailMap.get(style);
            if (!prev || detail.length > prev.length) {
              detailMap.set(style, detail);
            }
          }
        }
      }
    }
  }

  const keysShort = [...shortMap.keys()].sort();
  const linesShort = keysShort.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(shortMap.get(k))},`);
  const titlesBody = [
    "/* eslint-disable */",
    "// Auto-generated by scripts/generate-biz-care-collection-style-titles.mjs — do not edit.",
    "",
    "/** Biz Care / Biz Collection `*sum*.csv` short_description (grid + PDP when listing name is only `Brand SKU`). */",
    "export const BIZ_CARE_COLLECTION_STYLE_MARKETING_TITLE: Record<string, string> = {",
    ...linesShort,
    "};",
    "",
  ].join("\n");
  writeFileSync(join(root, "lib", "biz-care-collection-style-titles.generated.ts"), titlesBody, "utf8");
  console.log(`Wrote ${shortMap.size} Biz Care/Collection style titles → lib/biz-care-collection-style-titles.generated.ts`);

  const keysDetail = [...detailMap.keys()].sort();
  const linesDetail = keysDetail.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(detailMap.get(k))},`);
  const detailsBody = [
    "/* eslint-disable */",
    "// Auto-generated by scripts/generate-biz-care-collection-style-titles.mjs — do not edit.",
    "",
    "/** Biz Care / Biz Collection `*sum*.csv` stringified_description (PDP copy when DB description is empty or name-only). */",
    "export const BIZ_CARE_COLLECTION_STYLE_DETAIL_BODY: Record<string, string> = {",
    ...linesDetail,
    "};",
    "",
  ].join("\n");
  writeFileSync(join(root, "lib", "biz-care-collection-style-details.generated.ts"), detailsBody, "utf8");
  console.log(`Wrote ${detailMap.size} Biz Care/Collection style detail bodies → lib/biz-care-collection-style-details.generated.ts`);
}

main();
